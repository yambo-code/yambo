#!/bin/sh
# Generate content-stable build provenance for C and external audit tools.

set -eu

if [ "$#" -ne 3 ]; then
  echo "usage: $0 SOURCE_DIR OUTPUT_HEADER OUTPUT_MANIFEST" >&2
  exit 2
fi

srcdir=$1
header=$2
manifest=$3
release_manifest=$srcdir/include/version/release_provenance.txt

version=unknown
if [ -r "$srcdir/include/version/version.m4" ]; then
  version=$(awk -F '"' '
    /^SVERSION=/ { v=$2 }
    /^SSUBVERSION=/ { s=$2 }
    /^SPATCHLEVEL=/ { p=$2 }
    END { if (v != "" && s != "" && p != "") print v "." s "." p }
  ' "$srcdir/include/version/version.m4")
  [ -n "$version" ] || version=unknown
fi

commit=unknown
commit_short=unknown
ref=unknown
tag=unknown
state=unknown
source=unknown

read_manifest()
{
  [ -r "$1" ] || return 1
  while IFS='=' read -r key value; do
    case $key in
      version) version=$value ;;
      commit) commit=$value ;;
      commit_short) commit_short=$value ;;
      ref) ref=$value ;;
      tag) tag=$value ;;
      state) state=$value ;;
      source) source=$value ;;
    esac
  done < "$1"
  return 0
}

if command -v git >/dev/null 2>&1 &&
   commit=$(git -C "$srcdir" rev-parse --verify HEAD 2>/dev/null); then
  commit_short=$(git -C "$srcdir" rev-parse --short=12 HEAD 2>/dev/null || printf '%s' "$commit" | cut -c1-12)
  ref=$(git -C "$srcdir" symbolic-ref --quiet --short HEAD 2>/dev/null || printf '%s' detached)
  tag=$(git -C "$srcdir" describe --exact-match --tags HEAD 2>/dev/null || printf '%s' unknown)
  if git -C "$srcdir" diff --quiet --ignore-submodules HEAD -- 2>/dev/null; then
    state=clean
  else
    state=dirty
  fi
  source=git
elif read_manifest "$release_manifest"; then
  source=release-manifest
fi

override=no
if [ "${YAMBO_BUILD_COMMIT+x}" = x ]; then
  commit=$YAMBO_BUILD_COMMIT
  commit_short=$(printf '%s' "$commit" | cut -c1-12)
  override=yes
fi
if [ "${YAMBO_BUILD_REF+x}" = x ]; then ref=$YAMBO_BUILD_REF; override=yes; fi
if [ "${YAMBO_BUILD_TAG+x}" = x ]; then tag=$YAMBO_BUILD_TAG; override=yes; fi
if [ "${YAMBO_BUILD_DIRTY+x}" = x ]; then
  case $YAMBO_BUILD_DIRTY in
    1|yes|true|dirty) state=dirty ;;
    0|no|false|clean) state=clean ;;
    unknown|'') state=unknown ;;
    *) echo "invalid YAMBO_BUILD_DIRTY: $YAMBO_BUILD_DIRTY" >&2; exit 2 ;;
  esac
  override=yes
fi
if [ "${YAMBO_BUILD_SOURCE+x}" = x ]; then source=$YAMBO_BUILD_SOURCE; override=yes; fi
if [ "$override" = yes ] && [ "${YAMBO_BUILD_SOURCE+x}" != x ]; then source=ci-override; fi

[ -n "$commit" ] || commit=unknown
[ -n "$ref" ] || ref=unknown
[ -n "$tag" ] || tag=unknown
[ -n "$source" ] || source=unknown
if [ "$commit" != unknown ] && { [ "$commit_short" = unknown ] || [ -z "$commit_short" ]; }; then
  commit_short=$(printf '%s' "$commit" | cut -c1-12)
fi

# These limits match include/driver/kind.h and keep the manifest identical to
# the strings embedded in the executable.  Newlines are not valid field data.
version=$(printf '%s' "$version" | tr '\r\n' '  ' | cut -c1-31)
commit=$(printf '%s' "$commit" | tr '\r\n' '  ' | cut -c1-40)
commit_short=$(printf '%s' "$commit_short" | tr '\r\n' '  ' | cut -c1-12)
ref=$(printf '%s' "$ref" | tr '\r\n' '  ' | cut -c1-127)
tag=$(printf '%s' "$tag" | tr '\r\n' '  ' | cut -c1-127)
state=$(printf '%s' "$state" | tr '\r\n' '  ' | cut -c1-7)
source=$(printf '%s' "$source" | tr '\r\n' '  ' | cut -c1-31)

mkdir -p "$(dirname "$header")" "$(dirname "$manifest")"
header_tmp=$header.tmp.$$
manifest_tmp=$manifest.tmp.$$
trap 'rm -f "$header_tmp" "$manifest_tmp"' EXIT HUP INT TERM

c_escape()
{
  printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g'
}

cat > "$header_tmp" <<EOF
/* Generated by sbin/generate_build_provenance.sh.  Do not edit. */
#ifndef YAMBO_BUILD_PROVENANCE_H
#define YAMBO_BUILD_PROVENANCE_H
#define YAMBO_BUILD_VERSION "$(c_escape "$version")"
#define YAMBO_BUILD_COMMIT "$(c_escape "$commit")"
#define YAMBO_BUILD_COMMIT_SHORT "$(c_escape "$commit_short")"
#define YAMBO_BUILD_REF "$(c_escape "$ref")"
#define YAMBO_BUILD_TAG "$(c_escape "$tag")"
#define YAMBO_BUILD_STATE "$(c_escape "$state")"
#define YAMBO_BUILD_SOURCE "$(c_escape "$source")"
#endif
EOF

cat > "$manifest_tmp" <<EOF
version=$version
commit=$commit
commit_short=$commit_short
ref=$ref
tag=$tag
state=$state
source=$source
EOF

changed=no
if [ ! -r "$header" ] || ! cmp -s "$header_tmp" "$header"; then mv "$header_tmp" "$header"; changed=yes; fi
if [ ! -r "$manifest" ] || ! cmp -s "$manifest_tmp" "$manifest"; then mv "$manifest_tmp" "$manifest"; changed=yes; fi
if [ "$changed" = yes ]; then printf '%s\n' "$header"; fi
